<?php

/**
 * @file
 * Fills blank alt text on image media using the AI alt text generator.
 *
 * Written Nov 2026 for the 124 ARTEXPRESS images imported in 2025 whose AI
 * alt text call failed silently (the exhibitions import saved them blank).
 * Uses the same prompt/model as the import and the media Generate button
 * (Drupal\the_arts_unit_exhibitions\AltTextGenerator).
 *
 * Only touches media whose alt is blank or whitespace – never overwrites
 * existing alt text, including "." (fix those by hand in the alt text audit,
 * /admin/content/media/alt-text-audit).
 *
 * Usage (dry run by default – generates and prints suggestions, saves nothing,
 * but each suggestion is still a paid AI call):
 *   drush php:script private/scripts/backfill_blank_media_alt_text.php -- [apply] [limit=N] [mid=1,2,3]
 *
 *   apply        Save the generated alt text (new media revision).
 *   limit=N      Stop after N media (for test runs).
 *   mid=1,2,3    Only these media IDs.
 *
 * Live: /usr/local/bin/php -d memory_limit=1G vendor/drush/drush/drush.php
 *   php:script ../private/scripts/backfill_blank_media_alt_text.php --uri=https://LIVE-DOMAIN -- apply
 *
 * Writes a CSV of every result to
 * private://alt_text_backfill/backfill_YYYYmmdd-HHMMSS.csv.
 */

use Drupal\media\Entity\Media;
use Drupal\the_arts_unit_exhibitions\AltTextGenerator;

$apply = FALSE;
$limit = 0;
$only = [];
foreach ($extra ?? [] as $arg) {
  if ($arg === 'apply') {
    $apply = TRUE;
  }
  elseif (str_starts_with($arg, 'limit=')) {
    $limit = (int) substr($arg, 6);
  }
  elseif (str_starts_with($arg, 'mid=')) {
    $only = array_filter(array_map('intval', explode(',', substr($arg, 4))));
  }
  else {
    echo "Unknown argument: $arg\n";
    return;
  }
}

$db = \Drupal::database();
$query = $db->select('media__field_media_image', 'i');
$query->join('media_field_data', 'm', 'm.mid = i.entity_id AND m.langcode = i.langcode');
$query->fields('i', ['entity_id']);
$query->condition('i.bundle', 'image');
$query->condition('i.deleted', 0);
$query->where("TRIM(COALESCE(i.field_media_image_alt, '')) = ''");
if ($only) {
  $query->condition('i.entity_id', $only, 'IN');
}
$query->orderBy('i.entity_id');
if ($limit) {
  $query->range(0, $limit);
}
$mids = $query->execute()->fetchCol();

echo sprintf("%s: %d image media with blank alt text.\n", $apply ? 'APPLY' : 'DRY RUN', count($mids));
if (!$mids) {
  return;
}

$dir = 'private://alt_text_backfill';
\Drupal::service('file_system')->prepareDirectory($dir, \Drupal\Core\File\FileSystemInterface::CREATE_DIRECTORY);
$csv_path = $dir . '/backfill_' . date('Ymd-His') . ($apply ? '' : '_dryrun') . '.csv';
$csv = fopen($csv_path, 'w');
fputcsv($csv, ['mid', 'name', 'file', 'alt_text', 'status'], escape: '');

$saved = $failed = 0;
foreach ($mids as $i => $mid) {
  $media = Media::load($mid);
  $file = $media?->get('field_media_image')->entity;
  if (!$file) {
    fputcsv($csv, [$mid, $media?->label(), '', '', 'no file'], escape: '');
    echo "[$mid] no file – skipped\n";
    $failed++;
    continue;
  }

  $alt = AltTextGenerator::generate($file, $media->language()->getId() ?: 'en');
  if ($alt === NULL) {
    fputcsv($csv, [$mid, $media->label(), $file->getFilename(), '', 'AI failed'], escape: '');
    echo "[$mid] AI failed – see log\n";
    $failed++;
    continue;
  }

  // Re-check in case someone fixed it while the script was running.
  if ($apply && trim((string) $media->get('field_media_image')->alt) === '') {
    $media->get('field_media_image')->alt = $alt;
    $media->setNewRevision(TRUE);
    $media->setRevisionLogMessage('Alt text generated by AI (backfill_blank_media_alt_text.php).');
    $media->setRevisionCreationTime(\Drupal::time()->getRequestTime());
    $media->save();
    $saved++;
  }
  fputcsv($csv, [$mid, $media->label(), $file->getFilename(), $alt, $apply ? 'saved' : 'dry run'], escape: '');
  echo sprintf("[%d/%d] %d %s\n    → %s\n", $i + 1, count($mids), $mid, $media->label(), $alt);

  // Stay well under the provider's rate limits.
  usleep(500000);
}
fclose($csv);

echo sprintf("\nDone. %s %d, failed %d.\nCSV: %s\n", $apply ? 'Saved' : 'Generated (not saved)', $apply ? $saved : count($mids) - $failed, $failed, $csv_path);
